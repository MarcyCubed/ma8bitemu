/// List of Z80 prefixes or instructions with conditional execution
const Z80_COMPLICATED: [u8; 25] = [
    0xcb, 0xdd, 0xed, 0xfd, 0x10, 0x20, 0x28, 0x30, 0x38, 0xc0, 0xd0, 0xe0, 0xf0, 0xc4, 0xd4, 0xe4,
    0xf4, 0xc8, 0xd8, 0xe8, 0xf8, 0xcc, 0xdc, 0xec, 0xfc,
];

/// Test all instructions in the timing table, except the excluded ones
fn test_timing_simple_instructions<E: EmulatorCore>(
    new: fn() -> E,
    prefix: Option<u8>,
    exec_time: impl Fn(u8) -> u8,
    exclude: impl Fn(u8) -> bool,
) {
    for opcode in u8::MIN..=u8::MAX {
        // Don't test this one
        if exclude(opcode) {
            continue;
        }
        let mut emulator = new();
        let prefix = prefix.unwrap_or(opcode);
        let (cycles, _) = emulator.run_opcode(prefix, &mut memory::Constant(opcode));
        assert_eq!(
            exec_time(opcode),
            cycles,
            "Wrong number of clock cycles on instruction: {opcode:02x}h"
        );
    }
}

/// Test the timing of instructions without prefixes or conditional execution
#[test]
fn test_z80_simple_timing() {
    test_timing_simple_instructions(
        z80::Emulator::new,
        None,
        |opcode| Z80_TIMING[opcode as usize],
        |opcode| Z80_COMPLICATED.contains(&opcode),
    );
}

/// Test the timing of instructions in the 8080
#[test]
fn test_8080_simple_timing() {
    test_timing_simple_instructions(
        i8080::Emulator::new,
        None,
        |opcode| I8080_TIMING[opcode as usize],
        |opcode| Z80_COMPLICATED.contains(&opcode),
    );
}

/// Test the timing of instructions with ED prefix that run in constant time
#[test]
fn test_z80_ed_timing() {
    test_timing_simple_instructions(
        z80::Emulator::new,
        Some(0xed),
        |opcode| match (opcode >> 4, opcode & 0xf) {
            (4..=7, 0 | 1 | 8 | 9) => 12,
            (4..=7, 2 | 0xa) => 15,
            (4..=7, 0x3 | 0xb) => 20,
            (4, 4 | 6) | (5, 6 | 0xe) => 8,
            (4, 5 | 0xd) => 14,
            (4 | 5, 7 | 0xf) => 9,
            (6, 7 | 0xf) => 18,
            (0xa, 0..=3 | 8..=0xb) => 16,
            _ => 4,
        },
        |opcode| opcode >= 0xb0,
    );
}

/// Test the timing of instructions with DD or FD prefixes
#[test]
fn test_z80_ddfd_timing() {
    for prefix in [0xdd, 0xfd] {
        test_timing_simple_instructions(
            z80::Emulator::new,
            Some(prefix),
            |opcode| Z80_TIMING_INDEXED[opcode as usize],
            |opcode| Z80_COMPLICATED.contains(&opcode),
        );
    }
}

/// Test the timing of instructions with CB prefixes
#[test]
fn test_z80_cb_timing() {
    test_timing_simple_instructions(
        z80::Emulator::new,
        Some(0xcb),
        |opcode| match (opcode >> 4, opcode & 0xf) {
            (4..=7, 6 | 0xe) => 12,
            (_, 6 | 0xe) => 15,
            _ => 8,
        },
        |_| false,
    );
}

/// Test the timing of instructions with two prefixes
#[test]
fn test_z80_ddfd_cb_timing() {
    for prefix in [0xdd, 0xfd] {
        for opcode in 0x00..=0xff {
            for displacement in 0x00..=0xff {
                let mut emulator = z80::Emulator::new();
                let mut instruction =
                    memory::Repeat([prefix, 0xcb, displacement, opcode, 0, 0, 0, 0]);
                let (clock_cycles, _) = emulator.step(&mut instruction);

                let expected = match opcode {
                    0x40..=0x7f => 20,
                    _ => 23,
                };

                assert_eq!(
                    expected, clock_cycles,
                    "Wrong number of clock cycles on instruction: {opcode:02x}h clock cycles:{clock_cycles:?}"
                );
            }
        }
    }
}

fn test_conditional_flag_instruction<E: I8080FamilyEmulator>(
    new: fn() -> E,
    opcode: u8,
    min_cycles: u8,
    max_cycles: u8,
) {
    let cycles = [0, !0].map(|f_register| {
        let mut emulator = new();
        emulator.deserialize_flags(f_register);
        emulator.step(&mut memory::Constant(opcode)).0
    });
    assert_eq!(
        min_cycles,
        *cycles.iter().min().unwrap(),
        "Wrong number of clock cycles on instruction: {opcode:02x}h clock cycles:{cycles:?}"
    );
    assert_eq!(
        max_cycles,
        *cycles.iter().max().unwrap(),
        "Wrong number of clock cycles on instruction: {opcode:02x}h clock cycles:{cycles:?}"
    );
}

/// Test instructions whose execution time depend on the flags
#[test]
fn test_flag_instructions() {
    let instructions = [
        //(0x10, 8, 13), // djnz
        // jr cond
        (0x20, 7, 12, 0, 0),
        (0x30, 7, 12, 0, 0),
        (0x28, 7, 12, 0, 0),
        (0x38, 7, 12, 0, 0),
        // ret cond
        (0xc0, 5, 11, 5, 11),
        (0xd0, 5, 11, 5, 11),
        (0xe0, 5, 11, 5, 11),
        (0xf0, 5, 11, 5, 11),
        (0xc8, 5, 11, 5, 11),
        (0xd8, 5, 11, 5, 11),
        (0xe8, 5, 11, 5, 11),
        (0xf8, 5, 11, 5, 11),
        // call cond, nn
        (0xc4, 10, 17, 11, 17),
        (0xd4, 10, 17, 11, 17),
        (0xe4, 10, 17, 11, 17),
        (0xf4, 10, 17, 11, 17),
        (0xcc, 10, 17, 11, 17),
        (0xdc, 10, 17, 11, 17),
        (0xec, 10, 17, 11, 17),
        (0xfc, 10, 17, 11, 17),
    ];
    for (opcode, min_z80, max_z80, min_8080, max_8080) in instructions {
        test_conditional_flag_instruction(z80::Emulator::new, opcode, min_z80, max_z80);
        if min_8080 != 0 {
            test_conditional_flag_instruction(i8080::Emulator::new, opcode, min_8080, max_8080);
        }
    }
}

/// Test instructions that decrement BC and jump based on its value
#[test]
fn test_z80_bc_dec_jump() {
    let instructions = [
        (0xb0, 16, 21),
        (0xb1, 16, 21),
        (0xb8, 16, 21),
        (0xb9, 16, 21),
    ];
    for (opcode, min, max) in instructions {
        let mut emulator = z80::Emulator::new();
        let mut memory = memory::Repeat([0xed, opcode]);
        emulator.set_bc(2);

        let cycles = emulator.step(&mut memory).0;
        assert_eq!(
            max, cycles,
            "Wrong number of clock cycles on instruction: {opcode:02x}h clock cycles:{cycles:?}"
        );
        // Check if it's looping right and running the same instruction
        assert_eq!(0, emulator.pc.0);
        let cycles = emulator.step(&mut memory).0;
        assert_eq!(
            min, cycles,
            "Wrong number of clock cycles on instruction: {opcode:02x}h clock cycles:{cycles:?}"
        );
    }
}

/// Test the timing of inir and indr
#[test]
fn test_z80_inir_indr() {
    for opcode in [0xb2, 0xba] {
        let mut emulator = z80::Emulator::new();
        let mut memory = memory::Repeat([0xed, opcode]);
        emulator.b.0 = 2;
        let cycles = emulator.step(&mut memory).0;
        assert_eq!(
            21, cycles,
            "Wrong number of clock cycles on instruction: {opcode:02x}h clock cycles:{cycles:?}"
        );
        emulator.input(&mut memory, 0xff);
        // Check if it's looping right and running the same instruction
        assert_eq!(0, emulator.pc.0);
        let cycles = emulator.step(&mut memory).0;
        emulator.input(&mut memory, 0xff);
        assert_eq!(
            16, cycles,
            "Wrong number of clock cycles on instruction: {opcode:02x}h clock cycles:{cycles:?}"
        );
    }
}

/// Test the timing of djnz
#[test]
fn test_z80_djnz() {
    let mut emulator = z80::Emulator::new();
    let mut memory = memory::Constant(0x10); // djnz
    emulator.b.0 = 2;
    let cycles = emulator.step(&mut memory).0;
    assert_eq!(
        13, cycles,
        "Wrong number of clock cycles on DJNZ (10h). clock cycles:{cycles:?}"
    );
    emulator.input(&mut memory, 0xff);
    // Reset the PC
    emulator.pc.0 = 0;
    let cycles = emulator.step(&mut memory).0;
    emulator.input(&mut memory, 0xff);
    assert_eq!(
        8, cycles,
        "Wrong number of clock cycles on DJNZ (10h). clock cycles:{cycles:?}"
    );
}
